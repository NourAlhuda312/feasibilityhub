"use client";

import Link from "next/link";
import { useState } from "react";
import { useDemoState } from "@/lib/demo-state";

export default function PreviewSettingsPage() {
  const { state, reset } = useDemoState();
  const [invite, setInvite] = useState("");
  const [notice, setNotice] = useState("");

  function generate() {
    setInvite(`${window.location.origin}/join/course/DEMO-${Math.random().toString(36).slice(2, 10).toUpperCase()}`);
    setNotice("Demo course invite generated.");
  }

  async function copy(value: string, label: string) {
    try {
      await navigator.clipboard.writeText(value);
      setNotice(`${label} copied.`);
    } catch {
      setNotice("Copy was blocked by the browser. Select the value and copy it manually.");
    }
  }

  return <main className="min-h-screen p-5 sm:p-8"><div className="mx-auto max-w-4xl">
    <div className="flex items-center justify-between"><Link href="/preview/professor" className="text-sm font-black text-[#1f7a52]">← Dashboard</Link><button onClick={reset} className="rounded-xl border border-emerald-950/10 bg-white px-3 py-2 text-xs font-black">Reset demo</button></div>
    <h1 className="mt-6 text-4xl font-black tracking-[-.05em]">Course settings</h1>
    {notice && <div className="mt-5 rounded-2xl bg-blue-50 p-4 text-sm font-bold text-blue-900">{notice}</div>}
    <section className="surface mt-7 rounded-[30px] p-6"><div className="text-xs font-black uppercase tracking-[.14em] text-[#1f7a52]">Student access</div><div className="mt-2 text-xl font-black">Course join code</div><div className="mt-5 flex flex-wrap items-center gap-3"><div className="inline-flex rounded-2xl bg-[#173f2c] px-5 py-3 font-black tracking-[.12em] text-white">{state.course.joinCode}</div><button onClick={() => copy(state.course.joinCode, "Course code")} className="rounded-xl border border-emerald-950/10 bg-white px-3 py-2 text-xs font-black">Copy code</button></div></section>
    <section className="surface mt-5 rounded-[30px] p-6"><div className="text-xl font-black">Shareable invite</div>{invite && <div className="mt-4"><div className="break-all rounded-2xl bg-emerald-50 p-4 text-xs font-bold text-emerald-900">{invite}</div><button onClick={() => copy(invite, "Invite link")} className="mt-2 rounded-xl border border-emerald-950/10 bg-white px-3 py-2 text-xs font-black">Copy invite</button></div>}<button onClick={generate} className="primary-button mt-5 rounded-2xl px-5 py-3 text-sm font-black">Generate invite link</button></section>
    <section className="surface mt-5 rounded-[30px] p-6"><div className="text-xl font-black">Exports</div><p className="mt-2 text-sm text-stone-500">These demo export buttons download real CSV/XLSX files generated by the preview route.</p><div className="mt-5 flex gap-3"><a href="/api/export-demo?format=xlsx" className="primary-button rounded-2xl px-5 py-3 text-sm font-black">Excel (.xlsx)</a><a href="/api/export-demo?format=csv" className="rounded-2xl border border-emerald-950/15 bg-white px-5 py-3 text-sm font-black">CSV</a></div></section>
  </div></main>;
}
